def techniques_page(samples, techniques):
    md = [GENERATED, "", "[All samples](README.md)", "", "# Samples by technique", "",
          "A technique is one reusable idea you can carry to another agent or workflow.", ""]
    shown = 0
    for tid, t in techniques.items():
        users = [s for s in samples if tid in s.card["techniques"]]
        if not users:
            continue
        shown += 1
        md += [f'<a id="{tid}"></a>', "", f"## {t['title']}", "", t["summary"], ""]
        md += [f"- [{s.card['title']}](samples/{s.folder.name}/README.md): {s.card['summary']}" for s in users] + [""]
    if not shown:
        md += ["The index fills in as samples arrive.", ""]
    return "\n".join(md)


def catalogue(samples):
    out = []
    for s in sorted(samples, key=lambda x: x.folder.name.lower()):
        c, first = s.card, s.ladder()[0]
        e = {"id": c["id"], "title": c["title"], "summary": c["summary"], "kind": c["kind"], "category": c["category"],
             "level": c["level"], "version": s.version, "released": released(s), "techniques": c["techniques"],
             "quick_try_minutes": first["minutes"], "tested": c.get("tested") or [], "page": f"samples/{s.folder.name}/README.md"}
        if s.agent:
            e.update({"skills": len(s.agent.skills), "tools": len(s.agent.tools), "knowledge": len(s.agent.knowledge) + len(c.get("knowledge", []))})
        if s.workflow:
            e.update({"trigger": s.workflow.trigger, "inputs": len(s.workflow.inputs), "outputs": len(s.workflow.outputs),
                      "connections": s.workflow.connections})
        out.append(e)
    return json.dumps({"samples": out}, indent=2, ensure_ascii=False, default=str) + "\n"


def main():
    check = "--check" in sys.argv
    base = Path(sys.argv[sys.argv.index("--samples") + 1]).resolve() if "--samples" in sys.argv else ROOT / "samples"
    out_root = base.parent if "--samples" in sys.argv else ROOT
    techniques = yaml.safe_load((ROOT / "techniques.yml").read_text(encoding="utf-8"))
    categories = yaml.safe_load((ROOT / "categories.yml").read_text(encoding="utf-8"))
    samples, failed, pages = [], False, {}
    for card_path in sorted(base.glob("*/sample.yml"), key=lambda p: p.parent.name.lower()):
        s = Sample(card_path.parent, yaml.safe_load(card_path.read_text(encoding="utf-8")), techniques, categories)
        errors = s.errors()
        for e in errors:
            print(f"FAIL {s.folder.name}: {e}")
        if errors:
            failed = True
            continue
        for w in s.warnings():
            print(f"WARN {s.folder.name}: {w}")
        pages[s.folder / "README.md"] = s.overview()
        pages[s.folder / "SETUP.md"] = s.setup()
        samples.append(s)
        print(f"ok   {s.folder.name} ({s.kind})")
    pages[out_root / "README.md"] = gallery(samples, techniques, categories)
    pages[out_root / "TECHNIQUES.md"] = techniques_page(samples, techniques)
    pages[out_root / "samples.json"] = catalogue(samples)
    for path, text in pages.items():
        if check:
            if not path.exists() or path.read_text(encoding="utf-8") != text:
                print(f"FAIL {path.name} is stale, run tools/build_docs.py")
                failed = True
        elif not failed:
            path.write_text(text, encoding="utf-8")
    print(f"{len(samples)} sample(s)")
    sys.exit(1 if failed else 0)


if __name__ == "__main__":
    main()
