def released(s):
    cl = (s.folder / "CHANGELOG.md").read_text(encoding="utf-8")
    m = re.search(rf"^## {re.escape(s.version)} - (\d{{4}}-\d{{2}}-\d{{2}})", cl, re.M)
    return m.group(1) if m else ""


