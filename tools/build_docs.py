"""build_docs.py - writes the pages of every sample, the gallery, the index by technique and the catalogue.

    python tools/build_docs.py                        # write the pages
    python tools/build_docs.py --check                # fail (exit 1) when a page is stale or a card disagrees with its files
    python tools/build_docs.py --samples <folder>     # read the samples of another folder (drafts), pages written there

Two kinds of samples, both read from their own files, never typed twice:
  agent     samples/<id>/agent/<Agent name>/   the pac copilot workspace: settings.mcs.yml (name, model, instructions),
            behaviors/ (skills), capabilities/tools, capabilities/knowledge, workflows/, connectors/
  workflow  samples/<id>/workflows/<Name>-<guid>/metadata.yml + workflow.json: trigger, inputs, outputs, steps,
            connections ; tool/<Name>.mcs.yml when it is attached to an agent
For each sample: README.md (overview: Try it, problem, solution, what it does, how it works, design, limits, files,
tested on) and SETUP.md (one section per path, from the one that asks the least to the one that asks the most).
At the root: README.md (gallery), TECHNIQUES.md, samples.json.
"""
import json
import re
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REPO_URL = "https://github.com/PowerAutomateDesktop-CopilotStudio/copilot-studio-samples"
SEMVER = re.compile(r"\d+\.\d+\.\d+")
KIND = {"agent": "Agent", "workflow": "Workflow"}
GENERATED = "<!-- Generated by tools/build_docs.py from sample.yml and the sample files. Edit those, not this file. -->"
JSON_TYPES = {"string": "Text", "number": "Number", "integer": "Number", "boolean": "Boolean", "array": "List", "object": "Record"}
TRIGGERS = {"Skills": "When an agent calls the workflow", "Button": "Manual (Run button)", "Recurrence": "Recurrence"}
BUILD_TALK = re.compile(r"generated by|produced by|\b\w+[-_]\w+\.(?:py|ps1)\b", re.I)   # how a file was made is not for the reader


def anchor(title):
    return re.sub(r"[^a-z0-9]+", "-", title.lower()).strip("-")


def mcs(path):
    return yaml.safe_load(path.read_text(encoding="utf-8")) or {}


# ---------- reading an agent workspace ----------

class Agent:
    def __init__(self, ws: Path):
        self.ws = ws
        s = mcs(ws / "settings.mcs.yml")
        self.name = s.get("displayName", ws.name)
        self.schema = s.get("schemaName", "")
        agent = (s.get("configuration") or {}).get("agentSettings") or {}
        self.model = ((agent.get("model") or {}).get("series")) or ""
        segs = ((agent.get("instructions") or {}).get("segments")) or []
        self.instructions = "\n\n".join(seg.get("value", "") for seg in segs if seg.get("kind") == "StaticSegment").strip()
        self.skills, self.tools, self.knowledge = [], [], []
        for f in sorted((ws / "behaviors").glob("*.mcs.yml")) if (ws / "behaviors").exists() else []:
            d = mcs(f)
            if d.get("kind") != "InlineAgentSkill":
                continue
            meta = d.get("mcs.metadata") or {}
            pkg = ws / "behaviors" / f.name[:-len(".mcs.yml")]
            files = [p for p in pkg.rglob("*") if p.is_file() and not p.name.endswith(".mcs.yml")] if pkg.is_dir() else []
            self.skills.append({"name": meta.get("componentName", f.stem), "when": meta.get("description", ""),
                                "file": f.relative_to(ws.parent.parent).as_posix().replace(" ", "%20"), "package": len(files)})
        for kind, bucket in (("tools", self.tools), ("knowledge", self.knowledge)):
            folder = ws / "capabilities" / kind
            for f in sorted(folder.glob("*.mcs.yml")) if folder.exists() else []:
                d = mcs(f)
                meta = d.get("mcs.metadata") or {}
                src = d.get("source") or {}
                bucket.append({"name": meta.get("componentName", f.stem), "what": meta.get("description", ""),
                               "kind": d.get("kind", ""), "source": src.get("kind", ""), "url": src.get("siteUrl", "")})
        self.workflows = [Workflow(p) for p in sorted((ws / "workflows").iterdir())] if (ws / "workflows").exists() else []
        self.connectors = sorted(p.name for p in (ws / "connectors").iterdir()) if (ws / "connectors").exists() else []
        texts = [p.read_text(encoding="utf-8", errors="ignore") for p in ws.rglob("*.yml")]
        self.build_talk = sum(1 for t in texts if BUILD_TALK.search(t))


# ---------- reading a workflow ----------

class Workflow:
    def __init__(self, folder: Path):
        self.folder = folder
        m = mcs(folder / "metadata.yml")
        self.name, self.id, self.description = m.get("name", folder.name), str(m.get("workflowId", "")), m.get("description", "")
        d = json.loads((folder / "workflow.json").read_text(encoding="utf-8"))
        props = d.get("properties", d)
        df = props.get("definition", {})
        self.connections = sorted((props.get("connectionReferences") or {}).keys())
        trig = next(iter((df.get("triggers") or {}).values()), {})
        tkind = trig.get("kind") or trig.get("type", "")
        self.trigger = TRIGGERS.get(tkind, tkind)
        self.agent_tool = tkind == "Skills"
        self.inputs = self._fields((trig.get("inputs") or {}).get("schema") or {})
        self.actions = df.get("actions") or {}
        resp = next((a for a in self._walk(self.actions) if a.get("type") == "Response"), None)
        self.outputs = self._fields(((resp or {}).get("inputs") or {}).get("schema") or {})
        self.steps = [k.replace("_", " ") for k, v in sorted(self.actions.items(), key=lambda kv: self._order(kv, self.actions))]
        self.n_actions = sum(1 for _ in self._walk(self.actions))
        self.build_talk = 1 if BUILD_TALK.search(self.description or "") else 0

    @staticmethod
    def _fields(schema):
        req = set(schema.get("required") or [])
        return [{"name": k, "title": v.get("title", k), "type": JSON_TYPES.get(v.get("type", ""), v.get("type", "")), "what": v.get("description", ""),
                 "required": k in req} for k, v in (schema.get("properties") or {}).items()]

    @classmethod
    def _walk(cls, actions):
        for a in actions.values():
            yield a
            yield from cls._walk(a.get("actions") or {})
            for branch in ("else",):
                yield from cls._walk((a.get(branch) or {}).get("actions") or {})

    @staticmethod
    def _order(kv, actions):
        """Top-level steps in run order: follow runAfter."""
        depth, name, seen = 0, kv[0], set()
        while actions.get(name, {}).get("runAfter") and name not in seen:
            seen.add(name)
            name = next(iter(actions[name]["runAfter"]))
            depth += 1
        return depth


