        if c.get("design"):
            d = c["design"]
            md += ["## Design choices", "", d.get("intro", ""), ""]
            md += table(["Approach", "Result", "Verdict"], [[x["approach"], x["result"], x["verdict"]] for x in d.get("alternatives", [])])
