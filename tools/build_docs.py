def fig(p, width=None):
    w = f' width="{width}"' if width else ""
    return f'<img src="{p["file"]}" alt="{p["caption"]}"{w}><br><sub>{p["caption"]}</sub>'


def table(head, rows):
    return ["| " + " | ".join(head) + " |", "|" + "---|" * len(head)] + ["| " + " | ".join(r) + " |" for r in rows] + [""]


class Sample:
    def __init__(self, folder: Path, card: dict, techniques: dict, categories: dict):
        self.folder, self.card, self.techniques, self.categories = folder, card, techniques, categories
        self.kind = card.get("kind")
        self.version = str(card.get("version", ""))
        self.zip = f"{card.get('id')}-v{self.version}"
        self.pics = card.get("pictures") or {}
        self.agent, self.workflow, self.tool = None, None, None
        if self.kind == "agent" and (folder / "agent").exists():
            ws = [p for p in (folder / "agent").iterdir() if (p / "settings.mcs.yml").exists()]
            self.agent = Agent(ws[0]) if len(ws) == 1 else None
        if self.kind == "workflow" and (folder / "workflows").exists():
            wf = [p for p in (folder / "workflows").iterdir() if (p / "workflow.json").exists()]
            self.workflow = Workflow(wf[0]) if len(wf) == 1 else None
            tools = sorted((folder / "tool").glob("*.mcs.yml")) if (folder / "tool").exists() else []
            self.tool = tools[0] if tools else None
        self.tests = []
        csv_path = folder / "tests" / "test-set.csv"
        if csv_path.exists():
            import csv
            with csv_path.open(encoding="utf-8") as fh:
                self.tests = list(csv.DictReader(fh))

    def errors(self):
        c, err = self.card, []
        for key in ("id", "version", "title", "summary", "category", "kind", "level", "minutes", "problem", "solution",
                    "techniques", "quick_try", "tested"):
            if key not in c:
                err.append(f"{key}: required (see templates/{c.get('kind', 'agent')}/sample.yml)")
        if err:
            return err
        if c["id"] != self.folder.name:
            err.append(f"id: {c['id']} must be the folder name {self.folder.name}")
        if not SEMVER.fullmatch(self.version):
            err.append("version: x.y.z is required (1.0.0 for a new sample)")
        cl = self.folder / "CHANGELOG.md"
        if not cl.exists() or f"## {self.version}" not in cl.read_text(encoding="utf-8"):
            err.append(f"CHANGELOG.md: a section '## {self.version} - <date>' is required")
        if c["kind"] not in KIND:
            err.append(f"kind: must be one of {sorted(KIND)}")
        if c["category"] not in self.categories:
            err.append(f"category: '{c['category']}' is not in categories.yml")
        for t in c["techniques"]:
            if t not in self.techniques:
                err.append(f"techniques: '{t}' is not in techniques.yml")
        if c["kind"] == "agent":
            if not self.agent:
                err.append("agent/: exactly one agent workspace (a folder with settings.mcs.yml) is required")
            elif not self.agent.instructions:
                err.append("agent: settings.mcs.yml has no instructions")
            if not c["quick_try"].get("try"):
                err.append("quick_try.try: the messages to send in the quick try, each with what to expect")
        if c["kind"] == "workflow":
            if not self.workflow:
                err.append("workflows/: exactly one folder with metadata.yml and workflow.json is required")
            if "expect" not in c["quick_try"]:
                err.append("quick_try.expect: what the first run returns")
        return err

    def warnings(self):
        w = []
        if "result" not in self.pics:
            w.append("pictures.result: no picture of the result yet")
        if not self.card.get("tested"):
            w.append("tested: never tested yet - the pages say so")
        talk = (self.agent.build_talk if self.agent else 0) + (self.workflow.build_talk if self.workflow else 0)
        if talk:
            w.append("a file mentions how the sample was built (tools, scripts): keep only what a reader needs")
        return w

    def requires(self):
        return ", ".join(self.card.get("requires") or ["Copilot Studio"])

    def tested_line(self):
        t = self.card.get("tested") or []
        return f"Tested {t[-1]['date']}" if t else "**Not tested yet**"

    def meta(self):
        c = self.card
        return f"**{KIND[c['kind']]}** · {c['level'].capitalize()} · Requires {self.requires()} · {self.tested_line()} · v{self.version}"

    # --- the ladder, counted from the files ---
    def ladder(self):
        c, q = self.card, self.card["quick_try"]
        paths = []
        if self.kind == "agent":
            a = self.agent
            paths.append({"id": "quick", "title": "Quick try", "what": q.get("says", "The instructions pasted into a new agent."),
                          "asks": [], "needs": "Copilot Studio", "minutes": q.get("minutes", 5)})
            asks = ["the pac CLI signed in to an environment"]
            if a.skills:
                asks.append(f"{len(a.skills)} skill{'s' if len(a.skills) > 1 else ''} (pushed with the agent)")
            if c.get("knowledge"):
                asks.append(f"{len(c['knowledge'])} knowledge file{'s' if len(c['knowledge']) > 1 else ''} to add")
            if a.connectors or any(t["kind"] != "WorkflowTool" for t in a.tools):
                asks.append("connections to create")
            paths.append({"id": "full", "title": "Full agent", "what": "The agent as built: instructions, skills, tools, knowledge.",
                          "asks": asks, "needs": self.requires() + ", pac CLI", "minutes": c["minutes"]})
            if a.skills:
                paths.append({"id": "own", "title": "In your own agent", "what": "Add one of its skills to an agent you already have.",
                              "asks": ["one skill file pushed into your agent"], "needs": "Your agent, pac CLI", "minutes": None})
        else:
            w = self.workflow
            asks = ["an agent workspace to host it (pac CLI)"] + ([f"{len(w.connections)} connection(s)"] if w.connections else [])
            first = "Run it" if not w.agent_tool else "Call it from an agent"
            what = ("Push it, then run it with the sample inputs." if not w.agent_tool
                    else "Push it with its tool file into an agent, then ask the agent.")
            paths.append({"id": "quick", "title": first, "what": q.get("says", what), "asks": asks,
                          "needs": self.requires() + ", pac CLI", "minutes": q.get("minutes", 10)})
            paths.append({"id": "own", "title": "In your own agent or workflow", "what": "Reuse the steps, the inputs and outputs in your own build.",
                          "asks": ["the workflow folder, and the tool file for an agent"], "needs": "Your agent", "minutes": None})
        for i, p in enumerate(paths, 1):
            p["n"], p["anchor"] = i, f"{i}-{anchor(p['title'])}"
        return paths

    def ladder_table(self, prefix):
        rows = []
        for p in self.ladder():
            asks = ", ".join(p["asks"]) if p["asks"] else "Nothing: a new agent"
            asks = asks[0].upper() + asks[1:]
            time = f"{p['minutes']} min" if p["minutes"] is not None else "Depends on your build"
            rows.append([f"**[{p['n']}. {p['title']}]({prefix}#{p['anchor']})**<br>{p['what']}", asks, p["needs"], time])
        return table(["Path", "You create", "Needs", "Time"], rows)

